#!/usr/bin/env python3
"""Deterministic tool-call contract fixture, not a real AI model."""
import json
from http.server import BaseHTTPRequestHandler,ThreadingHTTPServer
class Handler(BaseHTTPRequestHandler):
 def do_POST(self):
  q=json.loads(self.rfile.read(int(self.headers['Content-Length'])))
  messages=q['messages'];text=next((m.get('content','') for m in reversed(messages) if m['role']=='user'),'')
  # Each UI test has its own conversation.
  observations=[m for m in messages if m['role']=='tool']
  msg={'role':'assistant','content':'Contract fixture reviewed the actual tool receipt.'}
  if not observations:
   action='command'
   cmd="printf 'uid='; id -u; cat owner.txt; printf 'generated by agent\\n' > agent-generated.txt; cat agent-generated.txt"
   if 'SLOW' in text:cmd="echo LIVE_PROGRESS; sleep 30; echo SHOULD_NOT_RUN"
   if 'FAIL' in text:cmd="echo ACTUAL_ERROR >&2; exit 7"
   if 'OTHER_A' in text:cmd='cat /home/icwqb_a/linux-agent-project/owner.txt'
   if 'OTHER_B' in text:cmd='cat /home/icwqb_b/linux-agent-project/owner.txt'
   msg={'role':'assistant','content':'I will execute the requested test and inspect its real exit code.','tool_calls':[{'id':'linux-test','type':'function','function':{'name':'linux_action','arguments':json.dumps({'action':action,'input':json.dumps({'command':cmd})})}}]}
  else:msg['content']+='\n'+observations[-1]['content']
  data=json.dumps({'choices':[{'message':msg}]}).encode();self.send_response(200);self.send_header('Content-Type','application/json');self.send_header('Content-Length',str(len(data)));self.end_headers();self.wfile.write(data)
 def log_message(self,*args):pass
ThreadingHTTPServer(('127.0.0.1',18882),Handler).serve_forever()
